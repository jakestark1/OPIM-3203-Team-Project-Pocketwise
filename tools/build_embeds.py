"""
Copies the CSV files into small JavaScript files so the app and the test page
work when index.html is opened straight from disk (browsers block reading
local files with fetch() on file:// pages).

Run after changing any CSV in sample-data/, tests/fixtures/ or tests/holdout/:
    python tools/build_embeds.py

Writes:
  js/sample-data.js   -> PW.SAMPLE_CSV (the "Try with sample data" statement)
  tests/fixtures.js   -> PW_FIXTURES  (test CSVs, answer keys, holdout statement)
"""
import base64
import json
import os

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
HEADER = "/* GENERATED by tools/build_embeds.py from the CSV files. Do not edit by hand. */\n"


def read(rel):
    with open(os.path.join(ROOT, rel), encoding="utf-8", newline="") as f:
        return f.read()


def main():
    sample = read("sample-data/sample-statement.csv")
    with open(os.path.join(ROOT, "js", "sample-data.js"), "w", encoding="utf-8", newline="\n") as f:
        f.write(HEADER)
        f.write("/* Made-up 3-month statement (Aug 1 - Oct 31, 2026) for a fictional person. */\n")
        f.write("window.PW = window.PW || {};\n")
        f.write("PW.SAMPLE_CSV = " + json.dumps(sample) + ";\n")

    fixtures = {"text": {}, "binary": {}}
    fixtures["text"]["sample-statement.csv"] = sample
    fixtures["text"]["answer-key.csv"] = read("sample-data/answer-key.csv")
    fixtures["text"]["holdout-boa.csv"] = read("tests/holdout/holdout-boa.csv")
    fixtures["text"]["holdout-answer-key.csv"] = read("tests/holdout/holdout-answer-key.csv")
    fdir = os.path.join(ROOT, "tests", "fixtures")
    for name in sorted(os.listdir(fdir)):
        path = os.path.join(fdir, name)
        if name.endswith(".csv"):
            fixtures["text"][name] = read(os.path.join("tests", "fixtures", name))
        else:
            with open(path, "rb") as f:
                fixtures["binary"][name] = base64.b64encode(f.read()).decode("ascii")
    with open(os.path.join(ROOT, "tests", "fixtures.js"), "w", encoding="utf-8", newline="\n") as f:
        f.write(HEADER)
        f.write("window.PW_FIXTURES = " + json.dumps(fixtures, indent=1) + ";\n")
    print("wrote js/sample-data.js and tests/fixtures.js with", len(fixtures["text"]), "text and",
          len(fixtures["binary"]), "binary fixtures")


if __name__ == "__main__":
    main()
